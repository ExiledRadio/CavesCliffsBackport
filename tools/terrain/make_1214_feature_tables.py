"""Writes terrain/core/FeatureTables1214.java from Oracle1214's table (tools/terrain/oracle-newer/v1214):
FeatureSorter's per-step order for each edition combination with the pale garden (Editions.PALE) and every
overworld biome's placed features in 1.21.4.

Usage: python tools/terrain/make_1214_feature_tables.py <oracle1214.txt> [version class]
(python tools/terrain/make_1214_feature_tables.py <oracle12111.txt> 1.21.11 FeatureTables12111 for Editions.SPRING)
"""
import io
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
core = os.path.join(here, '..', '..', 'src', 'main', 'java', 'com', 'exiledradio', 'cavesandcliffsbackport',
                    'terrain', 'core')
version = sys.argv[2] if len(sys.argv) > 2 else '1.21.4'
cls = sys.argv[3] if len(sys.argv) > 3 else 'FeatureTables1214'
out = os.path.join(core, cls + '.java')


def read(path):
    steps, biomes = {}, {}
    for line in io.open(path, encoding='utf-8'):
        head, _, rest = line.rstrip('\n').partition(' :')
        p = head.split()
        if p[0] == 'step':
            steps.setdefault(p[1], {})[int(p[2])] = rest.split()
        elif p[0] == 'biome':
            biomes.setdefault(p[1], {})[int(p[3])] = rest.split()
    return steps, biomes


steps, biomes = read(sys.argv[1])
names = re.search(r'NAMES = \{(.*?)\};', io.open(os.path.join(core, 'Biomes.java'), encoding='utf-8').read(), re.S)
biome_names = re.findall(r'"([^"]+)"', names.group(1))


def arr(ns):
    return '{' + ', '.join('"%s"' % n for n in ns) + '}'


def steps_block(name, doc, st):
    o = ['    /** %s */' % doc, '    static final String[][] %s = {' % name]
    for k in range(len(st)):
        o.append('        ' + arr(st[k]) + ',')
    o.append('    };')
    return o


o = ['package com.exiledradio.cavesandcliffsbackport.terrain.core;', '',
     '/**',
     " * %s's placed features per decoration step ({@link Editions#%s}), generated by" % (version, 'SPRING' if cls != 'FeatureTables1214' else 'PALE'),
     ' * tools/terrain/make_1214_feature_tables.py from the Oracle%s table (tools/terrain/oracle-newer): FeatureSorter over' % version.replace('.', ''),
     " * the biome source's biomes for each edition combination with the pale garden, and every overworld biome's list",
     " * (1.21.4 drops seagrass_simple from the oceans and adds ore_diamond_medium everywhere; 1.21.5's spring features are",
     " * placed outside the core, so they are skipped with their indexes kept). Do not edit by hand.",
     ' */',
     'final class %s {' % cls,
     '    private %s() {' % cls, '    }', '']
o += steps_block('STEPS_ALL', "WILD | CHERRY | PALE: %s's order." % version, steps['full'])
o.append('')
o += steps_block('STEPS_WILD', "WILD | PALE: without the cherry grove.", steps['wild+pale'])
o.append('')
o += steps_block('STEPS_CHERRY', "CHERRY | PALE: without the mangrove swamp and the deep dark.", steps['cherry+pale'])
o.append('')
o += steps_block('STEPS_PALE', "PALE alone: without the mangrove swamp, the deep dark and the cherry grove.", steps['pale'])
o.append('')
o.append("    /** Per biome id (Biomes), its placed features per step; empty for biomes outside the overworld. */")
o.append('    static final String[][][] BIOMES = {')
for i, n in enumerate(biome_names):
    st = biomes.get(n)
    if st is None:
        o.append('        {}, // %d %s' % (i, n))
        continue
    o.append('        { // %d %s' % (i, n))
    for k in range(max(st) + 1):
        o.append('            ' + arr(st.get(k, [])) + ',')
    o.append('        },')
o.append('    };')
o.append('}')
io.open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
print('wrote', out)
