"""Writes terrain/core/StructureTables.java from the oracle's structure_tables.txt (VanillaStructureDump).

Usage: python tools/terrain/make_structure_tables.py <oracle-out>/structure_tables.txt
"""
import io
import os
import sys

src = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', '..', 'src', 'main', 'java', 'com', 'exiledradio', 'cavesandcliffsbackport',
                   'terrain', 'core', 'StructureTables.java')

tags = []        # (set, index, name, weight, [ids])
ocean = []
pools = []       # (name, [(count, entry or None)])
portals = []     # (name, [ints])
current = None
for line in io.open(src, encoding='utf-8'):
    line = line.rstrip('\n')
    if not line or line.startswith('#'):
        continue
    if line.startswith('tag '):
        head, ids = line.split(':')
        parts = head.split()
        tags.append((parts[1], int(parts[2]), parts[3], int(parts[5]), [int(x) for x in ids.split()]))
    elif line.startswith('ocean_or_river'):
        ocean = [int(x) for x in line.split(':')[1].split()]
    elif line.startswith('pool '):
        parts = line.split()
        current = (parts[1], [])
        pools.append(current)
    elif line.startswith('  '):
        entry = None if line.strip() == 'empty' else tuple(int(x) for x in line.split())
        runs = current[1]
        if runs and runs[-1][1] == entry:
            runs[-1] = (runs[-1][0] + 1, entry)
        else:
            runs.append((1, entry))
    elif line.startswith('portal '):
        parts = line.split()
        portals.append((parts[1], [int(x) for x in parts[2:]]))

o = []
o.append('package com.exiledradio.cavesandcliffsbackport.terrain.core;')
o.append('')
o.append('/**')
o.append(' * 1.18.2 data the structure placement needs, generated by tools/terrain/make_structure_tables.py from the')
o.append(" * oracle's structure_tables.txt (VanillaStructureDump, read from vanilla's registries, biome tags and template")
o.append(' * files). Do not edit by hand.')
o.append(' */')
o.append('final class StructureTables {')
o.append('    private StructureTables() {')
o.append('    }')
o.append('')
o.append('    /** Per structure set (Structures.SET_*), per structure in the set: its biome tag as biome ids (Biomes). */')
sets = []
for t in tags:
    if t[0] not in sets:
        sets.append(t[0])
o.append('    static final int[][][] BIOMES = {')
for s in sets:
    rows = [t for t in tags if t[0] == s]
    o.append('        { // ' + s + ': ' + ', '.join(r[2] for r in rows))
    for r in rows:
        o.append('            {' + ', '.join(str(i) for i in r[4]) + '},')
    o.append('        },')
o.append('    };')
o.append('')
o.append('    /** Per structure set, per structure: its weight in the set. */')
o.append('    static final int[][] WEIGHTS = {')
for s in sets:
    o.append('        {' + ', '.join(str(t[3]) for t in tags if t[0] == s) + '}, // ' + s)
o.append('    };')
o.append('')
o.append('    /** Biomes of category OCEAN or RIVER (ocean monuments). */')
o.append('    static final int[] OCEAN_OR_RIVER = {' + ', '.join(str(i) for i in ocean) + '};')
o.append('')
o.append('    /**')
o.append("     * Start pools' templates lists (weight-expanded, as getRandomTemplate draws from them), run-length encoded: per run")
o.append('     * the count, then 0 for the empty element or 1, the ground level delta and for rotations NONE, CLOCKWISE_90,')
o.append('     * CLOCKWISE_180, COUNTERCLOCKWISE_90 the bounding box at the origin: minX, maxX, minZ, maxZ.')
o.append('     */')
o.append('    static final int[][] START_POOLS = {')
for name, runs in pools:
    vals = []
    for count, e in runs:
        if e is None:
            vals += [count, 0] + [0] * 17
        else:
            vals += [count, 1] + list(e)
    o.append('        { // ' + name)
    for i in range(0, len(vals), 19):
        o.append('            ' + ', '.join(str(v) for v in vals[i:i + 19]) + ',')
    o.append('        },')
o.append('    };')
o.append('')
o.append('    /**')
o.append('     * Ruined portal templates (portal_1..10, giant_portal_1..3): per rotation (NONE, CLOCKWISE_90, CLOCKWISE_180,')
o.append('     * COUNTERCLOCKWISE_90) and mirror (NONE, FRONT_BACK) the bounding box at the origin with its pivot: minX, maxX,')
o.append('     * minZ, maxZ, y span.')
o.append('     */')
o.append('    static final int[][] PORTALS = {')
for name, vals in portals:
    o.append('        {' + ', '.join(str(v) for v in vals) + '}, // ' + name)
o.append('    };')
o.append('}')
io.open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
print('wrote', out)
