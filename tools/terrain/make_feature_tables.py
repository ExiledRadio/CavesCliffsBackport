"""Writes terrain/core/FeatureTables.java from the oracle's feature_tables.txt (VanillaFeatureDump).

Usage: python tools/terrain/make_feature_tables.py <oracle-out>/feature_tables.txt
"""
import io
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', '..', 'src', 'main', 'java', 'com', 'exiledradio', 'cavesandcliffsbackport',
                   'terrain', 'core', 'FeatureTables.java')
steps = {}
biomes = {}
for line in io.open(sys.argv[1], encoding='utf-8'):
    head, _, rest = line.rstrip('\n').partition(' :')
    names = rest.split()
    parts = head.split()
    if parts[0] == 'step':
        steps[int(parts[1])] = names
    elif parts[0] == 'biome':
        biomes.setdefault(int(parts[1]), {})[int(parts[3])] = names


def arr(names):
    return '{' + ', '.join('"%s"' % n for n in names) + '}'


o = ['package com.exiledradio.cavesandcliffsbackport.terrain.core;', '',
     '/**',
     " * 1.18.2's placed features per decoration step, generated by tools/terrain/make_feature_tables.py from the",
     " * oracle's feature_tables.txt (VanillaFeatureDump). Do not edit by hand.",
     ' */',
     'final class FeatureTables {',
     '    private FeatureTables() {', '    }', '',
     '    /** Per step (GenerationStep.Decoration order), BiomeSource.featuresPerStep(): the index order of its features. */',
     '    static final String[][] STEPS = {']
for k in range(len(steps)):
    o.append('        ' + arr(steps[k]) + ',')
o.append('    };')
o.append('')
o.append("    /** Per biome id, per step: the biome's placed features (BiomeGenerationSettings.features()). */")
o.append('    static final String[][][] BIOMES = {')
for b in range(max(biomes) + 1):
    st = biomes.get(b, {})
    o.append('        { // ' + str(b))
    for k in range(max(st) + 1 if st else 0):
        o.append('            ' + arr(st.get(k, [])) + ',')
    o.append('        },')
o.append('    };')
o.append('}')
io.open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
print('wrote', out)
