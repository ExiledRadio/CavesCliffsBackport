"""Generates FossilTables.java from 1.18.2's fossil structure templates (data/minecraft/structures/fossil/*.nbt).

Usage: python make_fossil_tables.py <data dir, e.g. G:/mc1182data/data/minecraft/structures/fossil>

Each template's blocks come out in StructureTemplate.loadPalette's order: full collision blocks, then the others,
then blocks with NBT, each sorted by y, x, z (stable, as List.sort is). Fossils hold bone blocks and coal ore only,
all full blocks; the generator refuses anything else so a new block cannot slip in unclassified.
"""
import gzip
import os
import struct
import sys

NAMES = ["spine_1", "spine_2", "spine_3", "spine_4", "skull_1", "skull_2", "skull_3", "skull_4"]
FULL = {"minecraft:bone_block", "minecraft:coal_ore"}


class Reader:
    def __init__(self, data):
        self.d = data
        self.i = 0

    def take(self, n):
        b = self.d[self.i:self.i + n]
        self.i += n
        return b

    def u8(self):
        return self.take(1)[0]

    def i16(self):
        return struct.unpack(">h", self.take(2))[0]

    def i32(self):
        return struct.unpack(">i", self.take(4))[0]

    def string(self):
        n = struct.unpack(">H", self.take(2))[0]
        return self.take(n).decode("utf-8")

    def payload(self, t):
        if t == 1:
            return struct.unpack(">b", self.take(1))[0]
        if t == 2:
            return self.i16()
        if t == 3:
            return self.i32()
        if t == 4:
            return struct.unpack(">q", self.take(8))[0]
        if t == 5:
            return struct.unpack(">f", self.take(4))[0]
        if t == 6:
            return struct.unpack(">d", self.take(8))[0]
        if t == 7:
            return self.take(self.i32())
        if t == 8:
            return self.string()
        if t == 9:
            et = self.u8()
            return [self.payload(et) for _ in range(self.i32())]
        if t == 10:
            out = {}
            while True:
                ct = self.u8()
                if ct == 0:
                    return out
                name = self.string()
                out[name] = self.payload(ct)
        if t == 11:
            return [self.i32() for _ in range(self.i32())]
        if t == 12:
            return [struct.unpack(">q", self.take(8))[0] for _ in range(self.i32())]
        raise ValueError(t)


def load(path):
    r = Reader(gzip.open(path).read())
    t = r.u8()
    r.string()
    return r.payload(t)


def state_name(entry):
    name = entry["Name"]
    if name not in FULL:
        raise SystemExit("unclassified block " + name)
    props = entry.get("Properties", {})
    s = name[len("minecraft:"):]
    if props:
        s += "[" + ",".join(k + "=" + props[k] for k in sorted(props)) + "]"
    return s


def template(path):
    root = load(path)
    palette = [state_name(p) for p in (root["palettes"][0] if "palettes" in root else root["palette"])]
    full, other, nbt = [], [], []
    for b in root["blocks"]:
        x, y, z = b["pos"]
        info = (y, x, z, palette[b["state"]])
        (nbt if "nbt" in b else full).append(info)
    for lst in (full, other, nbt):
        lst.sort(key=lambda i: (i[0], i[1], i[2]))
    if "palettes" in root and len(root["palettes"]) != 1:
        raise SystemExit("more than one palette in " + path)
    return root["size"], full + other + nbt


def main():
    d = sys.argv[1]
    out = ["package com.exiledradio.cavesandcliffsbackport.terrain.core;", "",
           "/**",
           " * 1.18.2's fossil templates (structures/fossil), generated by tools/terrain/make_fossil_tables.py. Do not edit",
           " * by hand. Per template (FossilFeatureConfiguration order: spine_1..4, skull_1..4; COAL[i] is the _coal overlay):",
           " * the size, then per block x, y, z and its state, in StructureTemplate.loadPalette's order.",
           " */",
           "final class FossilTables {",
           "    private FossilTables() {",
           "    }", ""]
    for kind, suffix in (("BASE", ""), ("COAL", "_coal")):
        sizes, blocks, states = [], [], []
        for n in NAMES:
            size, infos = template(os.path.join(d, n + suffix + ".nbt"))
            sizes.append("{%d, %d, %d}" % tuple(size))
            blocks.append("{" + ", ".join("%d, %d, %d" % (x, y, z) for (y, x, z, s) in infos) + "}")
            st = sorted(set(s for (_, _, _, s) in infos))
            states.append((st, [st.index(s) for (_, _, _, s) in infos]))
        out.append("    static final int[][] %s_SIZE = {%s};" % (kind, ", ".join(sizes)))
        out.append("    static final int[][] %s_POS = {" % kind)
        for b in blocks:
            out.append("        " + b + ",")
        out.append("    };")
        out.append("    static final String[][] %s_STATES = {" % kind)
        for st, _ in states:
            out.append("        {" + ", ".join('"%s"' % s for s in st) + "},")
        out.append("    };")
        out.append("    static final byte[][] %s_STATE = {" % kind)
        for _, idx in states:
            out.append("        {" + ", ".join(str(i) for i in idx) + "},")
        out.append("    };")
        out.append("")
    out.append("}")
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "main", "java", "com",
                          "exiledradio", "cavesandcliffsbackport", "terrain", "core", "FossilTables.java")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(target))


if __name__ == "__main__":
    main()
