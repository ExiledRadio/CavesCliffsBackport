"""Writes terrain/core/NewerFeatureTables.java from the newer vanilla oracles (tools/terrain/oracle-newer):
FeatureSorter's per-step order for each edition and the new biomes' placed features.

Usage: python tools/terrain/make_newer_feature_tables.py <oracle119.txt> <oracle120.txt>
"""
import io
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', '..', 'src', 'main', 'java', 'com', 'exiledradio', 'cavesandcliffsbackport',
                   'terrain', 'core', 'NewerFeatureTables.java')


def read(path):
    steps, biomes = {}, {}
    for line in io.open(path, encoding='utf-8'):
        head, _, rest = line.rstrip('\n').partition(' :')
        p = head.split()
        if p[0] == 'step':
            steps.setdefault(p[1], {})[int(p[2])] = rest.split()
        elif p[0] == 'biome':
            biomes.setdefault(p[1], {})[int(p[3])] = rest.split()
    return steps, biomes


s119, b119 = read(sys.argv[1])
s120, b120 = read(sys.argv[2])


def arr(names):
    return '{' + ', '.join('"%s"' % n for n in names) + '}'


def steps_block(name, doc, steps):
    o = ['    /** %s */' % doc, '    static final String[][] %s = {' % name]
    for k in range(len(steps)):
        o.append('        ' + arr(steps[k]) + ',')
    o.append('    };')
    return o


def biome_block(name, doc, st):
    o = ['    /** %s */' % doc, '    static final String[][] %s = {' % name]
    for k in range(max(st) + 1):
        o.append('        ' + arr(st.get(k, [])) + ',')
    o.append('    };')
    return o


o = ['package com.exiledradio.cavesandcliffsbackport.terrain.core;', '',
     '/**',
     " * The newer versions' placed features per decoration step ({@link Editions}), generated by",
     ' * tools/terrain/make_newer_feature_tables.py from the oracles Oracle119 and Oracle120 (tools/terrain/oracle-newer).',
     " * FeatureSorter over the biome source's biomes; 1.18.2's biomes keep 1.18.2's features in every one (the oracles",
     ' * say so: tools/terrain/compare_newer.py), so only the order and the new biomes are here. Do not edit by hand.',
     ' */',
     'final class NewerFeatureTables {',
     '    private NewerFeatureTables() {', '    }', '']
o += steps_block('STEPS_WILD', "1.19.2's order (mangrove swamp and deep dark).", s119['full'])
o.append('')
o += steps_block('STEPS_BOTH', "1.20.1's order (mangrove swamp, deep dark, cherry grove).", s120['full'])
o.append('')
o += steps_block('STEPS_CHERRY', "1.20.1's order over its biomes without the mangrove swamp and the deep dark.", s120['nowild'])
o.append('')
o += biome_block('MANGROVE_SWAMP', "1.20.1's mangrove swamp (1.19.2's is the same).", b120['mangrove_swamp'])
o.append('')
o += biome_block('DEEP_DARK_119', "1.19.2's deep dark (ore_copper_large, which 1.20 changed to ore_copper).", b119['deep_dark'])
o.append('')
o += biome_block('DEEP_DARK', "1.20.1's deep dark.", b120['deep_dark'])
o.append('')
o += biome_block('CHERRY_GROVE', "1.20.1's cherry grove.", b120['cherry_grove'])
o.append('}')
if b119['mangrove_swamp'] != b120['mangrove_swamp']:
    sys.exit('the mangrove swamp differs between 1.19.2 and 1.20.1')
io.open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
print('wrote', out)
